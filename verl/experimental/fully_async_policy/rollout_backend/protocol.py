"""Structural API implemented by fully-async rollout backend actors."""

from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class RolloutBackend(Protocol):
    """Undecorated actor implementation API used by the unified entrypoint."""

    def get_capabilities(self) -> dict[str, Any]: ...

    async def init_workers(self) -> None: ...

    async def set_max_required_samples(self) -> None: ...

    async def set_message_queue_client(self, message_queue_client: Any) -> None: ...

    async def fit(self) -> None: ...

    async def request_stop(self) -> None: ...

    async def reset_staleness(self, version: int | None = None) -> dict[str, float]: ...

    async def sync_weights(self, version: int, hf_path: str) -> dict[str, float]: ...

    async def shutdown(self) -> None: ...
